create table public.quote_photos (
  id bigint generated by default as identity primary key,
  business_id bigint not null,
  quote_id bigint not null,
  storage_path text not null,
  original_name text not null,
  mime_type text not null,
  size_bytes bigint not null,
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint quote_photos_business_quote_fkey
    foreign key (business_id, quote_id)
    references public.quotes(business_id, id)
    on delete cascade,
  constraint quote_photos_storage_path_key unique (storage_path),
  constraint quote_photos_size_check check (size_bytes > 0 and size_bytes <= 6291456),
  constraint quote_photos_mime_check check (mime_type in ('image/jpeg', 'image/png', 'image/webp'))
);

create table public.quote_ai_threads (
  id bigint generated by default as identity primary key,
  business_id bigint not null,
  quote_id bigint not null,
  model text not null,
  prompt_version text not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint quote_ai_threads_business_quote_fkey
    foreign key (business_id, quote_id)
    references public.quotes(business_id, id)
    on delete cascade,
  constraint quote_ai_threads_business_quote_key unique (business_id, quote_id),
  constraint quote_ai_threads_business_id_key unique (business_id, id)
);

create table public.quote_ai_recommendations (
  id bigint generated by default as identity primary key,
  business_id bigint not null,
  quote_id bigint not null,
  thread_id bigint not null,
  response_id text,
  model text not null,
  prompt_version text not null,
  readiness text not null,
  confidence text not null,
  observations jsonb not null default '[]'::jsonb,
  questions jsonb not null default '[]'::jsonb,
  assumptions jsonb not null default '[]'::jsonb,
  risk_flags jsonb not null default '[]'::jsonb,
  suggested_scope text,
  suggested_price_low numeric(12,2),
  suggested_price_high numeric(12,2),
  recommended_price numeric(12,2),
  customer_message_draft text,
  applied_at timestamptz,
  applied_by uuid references auth.users(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint quote_ai_recommendations_business_quote_fkey
    foreign key (business_id, quote_id)
    references public.quotes(business_id, id)
    on delete cascade,
  constraint quote_ai_recommendations_business_thread_fkey
    foreign key (business_id, thread_id)
    references public.quote_ai_threads(business_id, id)
    on delete cascade,
  constraint quote_ai_recommendations_business_id_key unique (business_id, id),
  constraint quote_ai_recommendations_readiness_check
    check (readiness in ('ready', 'needs_information')),
  constraint quote_ai_recommendations_confidence_check
    check (confidence in ('low', 'medium', 'high')),
  constraint quote_ai_recommendations_prices_check
    check (
      (suggested_price_low is null or suggested_price_low >= 0)
      and (suggested_price_high is null or suggested_price_high >= 0)
      and (recommended_price is null or recommended_price >= 0)
      and (suggested_price_low is null or suggested_price_high is null or suggested_price_low <= suggested_price_high)
    )
);

create table public.quote_ai_messages (
  id bigint generated by default as identity primary key,
  business_id bigint not null,
  quote_id bigint not null,
  thread_id bigint not null,
  recommendation_id bigint,
  role text not null,
  content text not null,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint quote_ai_messages_business_quote_fkey
    foreign key (business_id, quote_id)
    references public.quotes(business_id, id)
    on delete cascade,
  constraint quote_ai_messages_business_thread_fkey
    foreign key (business_id, thread_id)
    references public.quote_ai_threads(business_id, id)
    on delete cascade,
  constraint quote_ai_messages_business_recommendation_fkey
    foreign key (business_id, recommendation_id)
    references public.quote_ai_recommendations(business_id, id)
    on delete set null (recommendation_id),
  constraint quote_ai_messages_role_check check (role in ('user', 'assistant')),
  constraint quote_ai_messages_content_check check (nullif(trim(content), '') is not null)
);

